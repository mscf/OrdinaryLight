"""Generate portable surface WGSL from typed OrdinaryShade graphics stages."""
import argparse
from pathlib import Path
import ordinaryshade as osh
from ordinarylight.shaders.portable_surface_programs import surface_vertex, surface_fragment


def generated_source():
    vertex = osh.compile(surface_vertex, target="wgsl").source
    fragment = osh.compile(surface_fragment, target="wgsl").source
    return ("// Generated by scripts/generate_portable_surface.py using OrdinaryShade.\n"
            + vertex.replace("fn main(", "fn vertex_main(").rstrip() + "\n\n"
            + fragment.replace("fn main(", "fn fragment_main(").rstrip() + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / "ordinarylight/portable/surface.wgsl"
    source = generated_source()
    if args.check:
        if target.read_text() != source:
            raise SystemExit(f"{target} is stale")
    else:
        target.write_text(source)
    print(("Verified " if args.check else "Wrote ") + target.name)


if __name__ == "__main__":
    main()
